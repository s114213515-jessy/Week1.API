-- Run against fastapi_dev as a database administrator.
-- This migration is safe to run more than once and does not modify W4/W5 data.

CREATE TABLE IF NOT EXISTS public.members (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    google_sub varchar(255) NOT NULL UNIQUE,
    email varchar(320) NOT NULL,
    name varchar(200),
    picture text,
    email_verified boolean NOT NULL DEFAULT TRUE,
    is_active boolean NOT NULL DEFAULT TRUE,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS members_email_idx ON public.members (email);

DO $grant_member_access$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'dev_user') THEN
        EXECUTE 'GRANT SELECT, INSERT, UPDATE ON public.members TO dev_user';
        EXECUTE 'GRANT USAGE, SELECT ON SEQUENCE public.members_id_seq TO dev_user';
    ELSE
        RAISE NOTICE 'Role dev_user does not exist; create it and re-run the grants';
    END IF;
END;
$grant_member_access$;
