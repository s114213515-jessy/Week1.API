-- Run with psql as a database administrator. This script creates the target
-- database if needed, then installs the academic schema, function, and view.
\if :{?DBName}
\else
\set DBName fastapi_dev
\endif

SELECT format('CREATE DATABASE %I', :'DBName')
WHERE NOT EXISTS (
    SELECT 1 FROM pg_database WHERE datname = :'DBName'
)
\gexec

\connect :DBName

BEGIN;

CREATE TABLE IF NOT EXISTS public.class (
    cid integer GENERATED BY DEFAULT AS IDENTITY,
    type smallint,
    name varchar(100) NOT NULL,
    des varchar(1000),
    idpath varchar(100),
    namepath varchar(200),
    create_at timestamp without time zone,
    update_at timestamp without time zone,
    nobject integer,
    crank smallint,
    orank smallint,
    code varchar(255),
    keywords varchar(255),
    nlevel smallint,
    imgid smallint,
    nclicktrue integer NOT NULL DEFAULT 0,
    nclick integer NOT NULL DEFAULT 0,
    property smallint NOT NULL DEFAULT 0,
    CONSTRAINT pk_class PRIMARY KEY (cid),
    CONSTRAINT uq_class_idpath UNIQUE (idpath),
    CONSTRAINT uq_class_namepath UNIQUE (namepath)
);

INSERT INTO public.class (cid, name, idpath, namepath)
VALUES (0, '首頁', '0', '首頁')
ON CONFLICT (cid) DO NOTHING;

CREATE TABLE IF NOT EXISTS public.inheritance (
    pcid integer NOT NULL,
    ccid integer NOT NULL,
    rank smallint,
    mg smallint,
    CONSTRAINT pk_inheritance PRIMARY KEY (pcid, ccid),
    CONSTRAINT fk_inheritance_pcid
        FOREIGN KEY (pcid) REFERENCES public.class (cid),
    CONSTRAINT fk_inheritance_ccid
        FOREIGN KEY (ccid) REFERENCES public.class (cid)
);

CREATE TABLE IF NOT EXISTS public.object (
    oid integer GENERATED BY DEFAULT AS IDENTITY,
    title varchar(200),
    class varchar(50),
    des varchar(1000),
    address varchar(400),
    telephone varchar(50),
    sourceurl varchar(400),
    nclick integer NOT NULL DEFAULT 0,
    CONSTRAINT pk_object PRIMARY KEY (oid)
);

CREATE TABLE IF NOT EXISTS public.co (
    cid integer NOT NULL,
    oid integer NOT NULL,
    rank smallint,
    mg smallint,
    CONSTRAINT pk_co PRIMARY KEY (cid, oid),
    CONSTRAINT fk_co_cid FOREIGN KEY (cid) REFERENCES public.class (cid),
    CONSTRAINT fk_co_oid FOREIGN KEY (oid) REFERENCES public.object (oid)
);

CREATE OR REPLACE FUNCTION public.insertclass(
    p_parent_id integer,
    p_parent_name varchar,
    p_child_name varchar
)
RETURNS integer
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $function$
DECLARE
    v_ccid integer;
    v_parent_idpath varchar(100);
    v_parent_namepath varchar(200);
    v_child_name varchar(100) := btrim(p_child_name);
BEGIN
    IF v_child_name IS NULL OR v_child_name = '' THEN
        RAISE EXCEPTION 'Child class name cannot be empty'
            USING ERRCODE = '23514';
    END IF;

    SELECT c.idpath, c.namepath
    INTO v_parent_idpath, v_parent_namepath
    FROM public.class AS c
    WHERE c.cid = p_parent_id AND c.name = btrim(p_parent_name)
    FOR UPDATE;

    IF NOT FOUND THEN
        IF EXISTS (SELECT 1 FROM public.class AS c WHERE c.cid = p_parent_id) THEN
            RAISE EXCEPTION 'Parent class name does not match cid %', p_parent_id
                USING ERRCODE = '23514';
        END IF;
        RAISE EXCEPTION 'Parent class with cid % does not exist', p_parent_id
            USING ERRCODE = '23503';
    END IF;

    SELECT c.cid
    INTO v_ccid
    FROM public.inheritance AS i
    JOIN public.class AS c ON c.cid = i.ccid
    WHERE i.pcid = p_parent_id AND c.name = v_child_name
    ORDER BY c.cid
    LIMIT 1;

    IF v_ccid IS NULL THEN
        INSERT INTO public.class (name)
        VALUES (v_child_name)
        RETURNING cid INTO v_ccid;
    END IF;

    INSERT INTO public.inheritance (pcid, ccid)
    VALUES (p_parent_id, v_ccid)
    ON CONFLICT ON CONSTRAINT pk_inheritance DO NOTHING;

    UPDATE public.class
    SET namepath = concat_ws('/', NULLIF(v_parent_namepath, ''), v_child_name),
        idpath = concat_ws('/', NULLIF(v_parent_idpath, ''), v_ccid::varchar)
    WHERE cid = v_ccid;

    RETURN v_ccid;
END;
$function$;

CREATE OR REPLACE VIEW public.vd_subclass AS
SELECT
    p.cid AS pcid,
    p.name AS parent_name,
    c.cid AS cid,
    c.name AS child_name
FROM public.class AS p
JOIN public.inheritance AS i ON i.pcid = p.cid
JOIN public.class AS c ON c.cid = i.ccid;

REVOKE ALL ON FUNCTION public.insertclass(integer, character varying, character varying)
    FROM PUBLIC;

DO $grant_academic_access$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'dev_user') THEN
        EXECUTE 'GRANT SELECT ON public.vd_subclass TO dev_user';
        EXECUTE 'GRANT SELECT (cid, name, idpath, namepath) ON public.class TO dev_user';
        EXECUTE 'GRANT EXECUTE ON FUNCTION public.insertclass(integer, character varying, character varying) TO dev_user';
    ELSE
        RAISE NOTICE 'Role dev_user does not exist; create it and re-run the grants';
    END IF;
END;
$grant_academic_access$;

COMMIT;
